use crate::model::AdapterResult;
use crate::yaml::Task;
use regex::{Regex, RegexBuilder};
use serde::Serialize;
use std::collections::HashSet;
use std::fs;
use std::path::Path;
use std::sync::OnceLock;

const TRIGGER: &str = r"\b(summarize|summary)\b.*\b(pr|pull request|diff)\b|\b(pr|pull request|diff)\b.*\b(summarize|summary)\b";

fn trigger_re() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        RegexBuilder::new(TRIGGER)
            .case_insensitive(true)
            .build()
            .expect("mock trigger regex")
    })
}

fn line_re(pattern: &str) -> Regex {
    RegexBuilder::new(pattern)
        .multi_line(true)
        .build()
        .expect("mock diff regex")
}

pub fn run_task(
    sandbox_dir: &Path,
    skill_dir: &Path,
    task: &Task,
    skill_name: &str,
) -> AdapterResult {
    let prompt = task.prompt_text();
    let triggered = trigger_re().is_match(&prompt);
    let mut result = AdapterResult::new("mock");
    let diff_path = sandbox_dir.join("pr.diff");
    let summary_path = sandbox_dir.join("summary.md");

    if !triggered {
        result.stdout = "I can help with other questions. (mock: skill not triggered)\n".into();
        return result;
    }

    result.skill_triggered = true;
    result.called_tools.push("Read".into());
    let diff = fs::read_to_string(&diff_path)
        .ok()
        .filter(|text| !text.trim().is_empty());
    let Some(diff) = diff else {
        result.stdout =
            "Error: pr.diff is missing or empty. Cannot summarize without a local pr.diff file.\n"
                .into();
        return result;
    };

    let title = derive_title(&diff);
    let bullets = derive_bullets(&diff);
    let body = format!(
        "# {title}\n\n{}\n",
        bullets
            .iter()
            .map(|bullet| format!("- {bullet}"))
            .collect::<Vec<_>>()
            .join("\n")
    );
    if let Err(err) = fs::write(&summary_path, &body) {
        result.error = Some(format!("failed to write summary.md: {err}"));
        result.stdout = result.error.clone().unwrap_or_default();
        return result;
    }
    result.called_tools.push("Write".into());
    result.files.insert("summary.md", body);
    let name = if skill_name.is_empty() {
        "summarize-pr"
    } else {
        skill_name
    };
    result.stdout = format!("Wrote summary.md ({name})\n");
    result.meta = Some(
        serde_json::to_value(MockMeta {
            skill_dir: skill_dir.display().to_string(),
        })
        .unwrap_or(serde_json::Value::Null),
    );
    result
}

#[derive(Serialize)]
struct MockMeta {
    #[serde(rename = "skillDir")]
    skill_dir: String,
}

fn derive_title(diff: &str) -> String {
    let re = line_re(r"^\+\+\+ b/(.+)$");
    if let Some(cap) = re.captures(diff) {
        format!("Update {}", cap[1].trim())
    } else {
        "PR summary".into()
    }
}

fn derive_bullets(diff: &str) -> Vec<String> {
    let added = line_re(r"^\+[^+]").find_iter(diff).count();
    let removed = line_re(r"^-[^-]").find_iter(diff).count();
    let file_re = line_re(r"^\+\+\+ b/(.+)$");
    let mut files = Vec::new();
    let mut seen = HashSet::new();
    for cap in file_re.captures_iter(diff) {
        let file = cap[1].trim().to_string();
        if seen.insert(file.clone()) {
            files.push(file);
        }
    }
    let touches = if files.is_empty() { 1 } else { files.len() };
    let list = if files.is_empty() {
        "(unknown)".to_string()
    } else {
        files.join(", ")
    };
    vec![
        format!("Touches {touches} file(s): {list}"),
        format!("Adds roughly {added} line(s) and removes {removed} line(s)"),
        "Generated by SkillParity mock harness (not a real LLM)".into(),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::yaml::Task;
    use std::fs;

    fn task(prompt: &str) -> Task {
        Task {
            id: Some("t".into()),
            prompt: Some(prompt.into()),
            fixture: None,
            expect: Default::default(),
        }
    }

    #[test]
    fn keyword_trigger_reads_diff_and_writes_summary() {
        let sandbox = tempfile::tempdir().unwrap();
        let diff = fs::read_to_string("examples/summarize-pr/fixtures/with-diff/pr.diff").unwrap();
        fs::write(sandbox.path().join("pr.diff"), &diff).unwrap();
        let skill = std::path::PathBuf::from("examples/summarize-pr");
        let result = run_task(
            sandbox.path(),
            &skill,
            &task("Please summarize this PR using the local pr.diff file."),
            "summarize-pr",
        );
        assert!(result.skill_triggered);
        assert_eq!(
            result.called_tools,
            vec!["Read".to_string(), "Write".to_string()]
        );
        let body = result.files.get("summary.md").unwrap();
        assert_eq!(
            body,
            "# Update src/hello.js\n\n- Touches 1 file(s): src/hello.js\n- Adds roughly 5 line(s) and removes 1 line(s)\n- Generated by SkillParity mock harness (not a real LLM)\n"
        );
        assert_eq!(
            fs::read_to_string(sandbox.path().join("summary.md")).unwrap(),
            body
        );
        assert_eq!(
            result.meta.as_ref().unwrap()["skillDir"],
            "examples/summarize-pr"
        );
    }

    #[test]
    fn unrelated_prompt_does_not_trigger() {
        let sandbox = tempfile::tempdir().unwrap();
        let result = run_task(
            sandbox.path(),
            Path::new("examples/summarize-pr"),
            &task("What's the weather in Tokyo today?"),
            "summarize-pr",
        );
        assert!(!result.skill_triggered);
        assert!(result.called_tools.is_empty());
        assert!(result.files.is_empty());
        assert!(result.stdout.contains("not triggered"));
        assert!(result.meta.is_none());
    }

    #[test]
    fn missing_diff_fails_clearly() {
        let sandbox = tempfile::tempdir().unwrap();
        let result = run_task(
            sandbox.path(),
            Path::new("examples/summarize-pr"),
            &task("Summarize the pull request from pr.diff."),
            "summarize-pr",
        );
        assert!(result.skill_triggered);
        assert_eq!(result.called_tools, vec!["Read".to_string()]);
        assert!(result.files.is_empty());
        assert!(result.stdout.to_lowercase().contains("missing"));
        assert!(!sandbox.path().join("summary.md").exists());
    }
}
