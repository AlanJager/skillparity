/**
 * Always-available harness adapter for CI without Claude.
 * Simulates skill trigger from prompt keywords; writes summary.md when pr.diff exists.
 */
import fs from "node:fs";
import path from "node:path";

const TRIGGER_RE =
  /\b(summarize|summary)\b.*\b(pr|pull request|diff)\b|\b(pr|pull request|diff)\b.*\b(summarize|summary)\b/i;

export const name = "mock";

/**
 * @param {object} opts
 * @param {string} opts.sandboxDir
 * @param {string} opts.skillDir
 * @param {object} opts.task  — { id, prompt, fixture?, expect? }
 * @param {string} opts.skillName
 */
export async function runTask({ sandboxDir, skillDir, task, skillName }) {
  const prompt = task.prompt || "";
  const triggered = TRIGGER_RE.test(prompt);
  const called_tools = [];
  let stdout = "";
  const files = {};

  const diffPath = path.join(sandboxDir, "pr.diff");
  const summaryPath = path.join(sandboxDir, "summary.md");

  if (!triggered) {
    stdout = "I can help with other questions. (mock: skill not triggered)\n";
    return {
      skill_triggered: false,
      called_tools,
      files,
      stdout,
      harness: name,
    };
  }

  // Skill path: try to read pr.diff
  called_tools.push("Read");
  let diff = null;
  if (fs.existsSync(diffPath)) {
    diff = fs.readFileSync(diffPath, "utf8");
  }

  if (diff == null || diff.trim() === "") {
    stdout =
      "Error: pr.diff is missing or empty. Cannot summarize without a local pr.diff file.\n";
    return {
      skill_triggered: true,
      called_tools,
      files,
      stdout,
      harness: name,
    };
  }

  // Produce a deterministic summary from the fake diff
  const title = deriveTitle(diff);
  const bullets = deriveBullets(diff);
  const body = `# ${title}\n\n${bullets.map((b) => `- ${b}`).join("\n")}\n`;
  fs.writeFileSync(summaryPath, body, "utf8");
  called_tools.push("Write");
  files["summary.md"] = body;
  stdout = `Wrote summary.md (${skillName || "summarize-pr"})\n`;

  // Also record skill dir was consulted (Read SKILL.md conceptually)
  return {
    skill_triggered: true,
    called_tools,
    files,
    stdout,
    harness: name,
    meta: { skillDir },
  };
}

function deriveTitle(diff) {
  const m = diff.match(/^\+\+\+ b\/(.+)$/m);
  if (m) return `Update ${m[1].trim()}`;
  return "PR summary";
}

function deriveBullets(diff) {
  const added = (diff.match(/^\+[^+]/gm) || []).length;
  const removed = (diff.match(/^-[^-]/gm) || []).length;
  const files = new Set(
    [...diff.matchAll(/^\+\+\+ b\/(.+)$/gm)].map((x) => x[1].trim())
  );
  return [
    `Touches ${files.size || 1} file(s): ${[...files].join(", ") || "(unknown)"}`,
    `Adds roughly ${added} line(s) and removes ${removed} line(s)`,
    "Generated by SkillParity mock harness (not a real LLM)",
  ];
}
